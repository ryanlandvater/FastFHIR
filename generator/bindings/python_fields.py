def emit_python_fields_init(
    python_resource_map: dict[str, dict[str, tuple]], output_dir: str = "generated_src"
) -> None:
    """Emit fields/__init__.py re-exporting every resource field schema.

    Without a real package init the generated per-resource modules form a PEP 420
    namespace package, so `from fastfhir.fields import Patient` fails (TASKS.md A21)
    for both the staged build-tree package and the installed one. Called after
    emit_python_ast so base.py is written in the same run.
    """
    target_dir = os.path.join(output_dir, "python", "fields")
    os.makedirs(target_dir, exist_ok=True)
    class_names = sorted(python_resource_map.keys())
    lines = [
        "# Auto-generated by FastFHIR pipeline. Do not edit.",
        '"""Generated per-resource field schemas."""',
        "",
        "from .base import ASTNode, ASTArrayNode",
        "",
    ]
    lines += [f"from .{name.lower()} import {name}" for name in class_names]
    lines += ["", "__all__ = ["]
    lines += [f'    "{name}",' for name in class_names]
    lines += ['    "ASTNode",', '    "ASTArrayNode",', "]"]
    with open(os.path.join(target_dir, "__init__.py"), "w") as f:
        f.write("\n".join(lines) + "\n")
